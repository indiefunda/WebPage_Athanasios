/**
 * Downloads the site's typefaces from Google Fonts as self-hosted WOFF2,
 * keeping only the Latin and Greek subsets, and writes src/styles/fonts.css.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'public', 'fonts');
const CSS_OUT = path.join(ROOT, 'src', 'styles', 'fonts.css');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const FAMILIES = [
  {
    // Greek Didot: high-contrast display serif with native Greek.
    query: 'GFS+Didot',
    slug: 'gfs-didot',
    family: 'GFS Didot',
    subsets: ['greek', 'greek-ext', 'latin', 'latin-ext'],
  },
  {
    // Contemporary geometric sans with Greek support.
    query: 'Manrope:wght@200..800',
    slug: 'manrope',
    family: 'Manrope',
    subsets: ['greek', 'greek-ext', 'latin', 'latin-ext'],
  },
];

const KEEP = new Set(['greek', 'greek-ext', 'latin', 'latin-ext']);

await mkdir(FONT_DIR, { recursive: true });
await mkdir(path.dirname(CSS_OUT), { recursive: true });

let css = `/* Self-hosted webfonts. Generated by scripts/download-fonts.mjs — do not edit by hand. */\n\n`;

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${family.family}: ${res.status}`);
  const sheet = await res.text();

  // Google Fonts emits "/* subset */" immediately before each @font-face block.
  const blockPattern = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/gi;
  let match;
  let count = 0;

  while ((match = blockPattern.exec(sheet))) {
    const subset = match[1].toLowerCase();
    const block = match[2];
    if (!KEEP.has(subset)) continue;

    const srcMatch = block.match(/url\((https:\/\/[^)]+\.woff2)\)/);
    if (!srcMatch) continue;
    const remote = srcMatch[1];

    const weight = (block.match(/font-weight:\s*([^;]+);/) || [, '400'])[1].trim();
    const style = (block.match(/font-style:\s*([^;]+);/) || [, 'normal'])[1].trim();
    const unicodeRange = (block.match(/unicode-range:\s*([^;]+);/) || [, ''])[1].trim();

    const fileName = `${family.slug}-${subset}${style === 'italic' ? '-italic' : ''}.woff2`;
    const localPath = path.join(FONT_DIR, fileName);

    const fontRes = await fetch(remote, { headers: { 'User-Agent': UA } });
    if (!fontRes.ok) throw new Error(`${fileName}: ${fontRes.status}`);
    await writeFile(localPath, Buffer.from(await fontRes.arrayBuffer()));

    css += `/* ${family.family} — ${subset} */\n@font-face {\n`;
    css += `  font-family: '${family.family}';\n`;
    css += `  font-style: ${style};\n`;
    css += `  font-weight: ${weight};\n`;
    css += `  font-display: swap;\n`;
    css += `  src: url('/fonts/${fileName}') format('woff2');\n`;
    if (unicodeRange) css += `  unicode-range: ${unicodeRange};\n`;
    css += `}\n\n`;

    count += 1;
    console.log(`  ${fileName.padEnd(34)} ${weight}`);
  }

  console.log(`${family.family}: ${count} files`);
}

await writeFile(CSS_OUT, css);
console.log(`Wrote ${path.relative(ROOT, CSS_OUT)}`);
